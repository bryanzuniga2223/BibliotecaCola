        private void actualizarCampos() {
        String tipo = (String) cmbTipo.getSelectedItem();
        txtPaginas.setEnabled("Libro".equals(tipo));
        txtEdicion.setEnabled("Revista".equals(tipo));
        txtConferencia.setEnabled("Articulo".equals(tipo));
        if (!txtPaginas.isEnabled()) txtPaginas.setText("");
        if (!txtEdicion.isEnabled()) txtEdicion.setText("");
        if (!txtConferencia.isEnabled()) txtConferencia.setText("");
    }

    private String leerTexto(JTextField campo, String nombre) {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" no puede estar vacío.");
        }
        return texto;
    }

    private int leerEntero(JTextField campo, String nombre) {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" no puede estar vacío.");
        }
        int valor;
        try {
            valor = Integer.parseInt(texto);
        } catch (NumberFormatException e) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" debe ser un número entero.");
        }
        if (valor <= 0) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" debe ser mayor a cero.");
        }
        return valor;
    }

    private Trabajo crearTrabajo() {
        String titulo = leerTexto(txtTitulo, "Título");
        String autor = leerTexto(txtAutor, "Autor");
        int anio = leerEntero(txtAnio, "Año de publicación");
        String tipo = (String) cmbTipo.getSelectedItem();

        switch (tipo) {
            case "Libro":
                return new Libro(titulo, autor, anio, leerEntero(txtPaginas, "Número de páginas"));
            case "Revista":
                return new Revista(titulo, autor, anio, leerEntero(txtEdicion, "Número de edición"));
            default:
                return new Articulo(titulo, autor, anio, leerTexto(txtConferencia, "Nombre de la conferencia"));
        }
    }

    private void limpiarCampos() {
        txtTitulo.setText("");
        txtAutor.setText("");
        txtAnio.setText("");
        txtPaginas.setText("");
        txtEdicion.setText("");
        txtConferencia.setText("");
        txtTitulo.requestFocus();
    }

    private void actualizarVista() {
        StringBuilder sb = new StringBuilder();
        sb.append("COLA DE TRABAJOS (FIFO)   -   Elementos: ").append(cola.size()).append("\n\n");

        if (cola.isEmpty()) {
            sb.append("(La cola está vacía)");
        } else {
            Trabajo[] trabajos = cola.toArray();
            for (int i = 0; i < trabajos.length; i++) {
                String marca;
                if (trabajos.length == 1) {
                    marca = "FRENTE/FINAL -> ";
                } else if (i == 0) {
                    marca = "FRENTE       -> ";
                } else if (i == trabajos.length - 1) {
                    marca = "FINAL        -> ";
                } else {
                    marca = "                ";
                }
                sb.append(marca).append(i + 1).append(". ").append(trabajos[i]).append("\n");
            }
        }
        txtAreaCola.setText(sb.toString());
    }

