    private void btnEncolarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEncolarActionPerformed
        try {
            Trabajo nuevo = crearTrabajo();
            cola.offer(nuevo);
            actualizarVista();
            limpiarCampos();
            JOptionPane.showMessageDialog(this,
                    "Trabajo encolado al FINAL:\n" + nuevo,
                    "Encolar (Offer)", JOptionPane.INFORMATION_MESSAGE);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnEncolarActionPerformed

    private void btnVaciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVaciarActionPerformed
        if (cola.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "La cola ya está vacía.\nisEmpty() = " + cola.isEmpty(),
                    "Vaciar Cola", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Vaciar la cola? Se eliminarán " + cola.size() + " trabajo(s).",
                "Vaciar Cola", JOptionPane.YES_NO_OPTION);
        if (respuesta == JOptionPane.YES_OPTION) {
            cola.vaciarCola();
            actualizarVista();
            JOptionPane.showMessageDialog(this,
                    "La cola se vació correctamente.\nisEmpty() = " + cola.isEmpty(),
                    "Vaciar Cola", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnVaciarActionPerformed

    private void btnAtenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtenderActionPerformed
        try {
            Trabajo atendido = cola.poll();
            actualizarVista();
            JOptionPane.showMessageDialog(this,
                    "Trabajo atendido (salió del FRENTE):\n" + atendido
                    + "\n\nQuedan en la cola: " + cola.size(),
                    "Atender (Poll)", JOptionPane.INFORMATION_MESSAGE);
        } catch (IllegalStateException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cola vacía", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnAtenderActionPerformed

    private void btnFrenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFrenteActionPerformed
        try {
            Trabajo primero = cola.peek();
            JOptionPane.showMessageDialog(this,
                    "Trabajo en el FRENTE (no se removió):\n" + primero
                    + "\n\nElementos en la cola: " + cola.size(),
                    "Consultar Frente (Peek)", JOptionPane.INFORMATION_MESSAGE);
        } catch (IllegalStateException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cola vacía", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnFrenteActionPerformed

